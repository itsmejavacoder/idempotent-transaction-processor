CREATE TABLE IF NOT EXISTS transactions (
    transaction_id VARCHAR(100) PRIMARY KEY,
    request_id VARCHAR(100) NOT NULL,
    account_id VARCHAR(100) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    sequence_number BIGINT NOT NULL,
    failures_before_success INT NOT NULL DEFAULT 0,
    attempts INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL,
    last_error VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_transactions_request_id UNIQUE (request_id),
    CONSTRAINT uq_transactions_sequence_number UNIQUE (sequence_number)
);

CREATE INDEX IF NOT EXISTS idx_transactions_work
    ON transactions(status, sequence_number);

CREATE TABLE IF NOT EXISTS accounts (
    account_id VARCHAR(100) PRIMARY KEY,
    balance DECIMAL(19, 2) NOT NULL DEFAULT 0,
    last_sequence BIGINT NOT NULL DEFAULT 0,
    currency VARCHAR(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    account_id VARCHAR(100) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    balance_after DECIMAL(19, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ledger_transaction_id UNIQUE (transaction_id)
);

CREATE INDEX IF NOT EXISTS idx_ledger_account ON ledger_entries(account_id);

-- Single-row stream that gives the service a global, gap-aware ordering point.
CREATE TABLE IF NOT EXISTS processing_stream (
    id INT PRIMARY KEY,
    last_sequence BIGINT NOT NULL DEFAULT 0
);

INSERT INTO processing_stream (id, last_sequence)
SELECT 1, 0 WHERE NOT EXISTS (SELECT 1 FROM processing_stream WHERE id = 1);

-- Every duplicate attempt is retained so duplicate counts survive restarts.
CREATE TABLE IF NOT EXISTS duplicate_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    request_id VARCHAR(100) NOT NULL,
    reason VARCHAR(200) NOT NULL,
    detected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_duplicates_transaction ON duplicate_requests(transaction_id);

-- Append-only state transition history for traceability.
CREATE TABLE IF NOT EXISTS transaction_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    detail VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_transaction_events_transaction ON transaction_events(transaction_id, id);
